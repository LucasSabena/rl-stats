/**
 * Regenerates src/lib/arenaImages.ts from whatever is actually in
 * public/arenas/, and reports any mapped arena still missing an image.
 *
 * Run with: pnpm assets:arenas
 */
import { readdir, writeFile, readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const arenaDir = path.join(root, "public", "arenas");
const outFile = path.join(root, "src", "lib", "arenaImages.ts");

const files = await readdir(arenaDir);
const keys = files
  .filter((f) => f.endsWith(".webp"))
  .map((f) => f.replace(/\.webp$/, ""))
  .sort();

const banner = `// AUTO-GENERATED by scripts/generate-arena-manifest.mjs — do not edit by hand.
// Regenerate with: pnpm assets:arenas
`;

await writeFile(
  outFile,
  `${banner}
export const ARENA_IMAGE_KEYS: readonly string[] = [
${keys.map((k) => `  "${k}",`).join("\n")}
];
`,
  "utf8",
);

// Cross-check against the map so gaps are visible rather than silent.
const mapSource = await readFile(path.join(root, "src", "lib", "arenaMap.ts"), "utf8");
const mapped = [...mapSource.matchAll(/^ {2}([a-z0-9_]+):\s*\{/gm)].map((m) => m[1]);
const aliased = new Set(
  [...mapSource.matchAll(/imageFrom:\s*"([a-z0-9_]+)"/g)].map((m) => m[1]),
);

const withImage = new Set(keys);
const missing = mapped.filter((k) => {
  if (withImage.has(k)) return false;
  // An arena that borrows another's image is covered.
  const block = mapSource.slice(mapSource.indexOf(`  ${k}: {`));
  const close = block.indexOf("}");
  return !/imageFrom:/.test(block.slice(0, close));
});

console.log(`${keys.length} arena images -> ${path.relative(root, outFile)}`);
if (aliased.size) console.log(`${aliased.size} arena(s) reuse another arena's image`);
if (missing.length) {
  console.log(`\n${missing.length} mapped arena(s) with no image (generated tile will be used):`);
  for (const k of missing) console.log(`  - ${k}`);
}
